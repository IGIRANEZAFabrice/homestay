    <script>
        // Smooth scrolling for navigation pills
        document.querySelectorAll('.nav-pill').forEach(pill => {
            pill.addEventListener('click', function(e) {
                e.preventDefault();
                const targetId = this.getAttribute('href');
                const targetElement = document.querySelector(targetId);
                if (targetElement) {
                    targetElement.scrollIntoView({
                        behavior: 'smooth',
                        block: 'start'
                    });
                }
            });
        });

        // Add scroll animations
        const observerOptions = {
            threshold: 0.1,
            rootMargin: '0px 0px -50px 0px'
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    if (entry.target.classList.contains('program-card') || 
                        entry.target.classList.contains('stat-card') ||
                        entry.target.classList.contains('travel-item')) {
                        entry.target.classList.add('animate-fadeIn');
                    }
                }
            });
        }, observerOptions);

        // Observe elements for animation
        document.querySelectorAll('.program-card, .stat-card, .travel-item, .gallery-item').forEach(el => {
            observer.observe(el);
        });

        // Counter animation for statistics
        function animateCounter(element) {
            const target = parseInt(element.textContent.replace(/[^0-9]/g, ''));
            const prefix = element.textContent.replace(/[0-9]/g, '');
            let current = 0;
            const increment = target / 30;
            const timer = setInterval(() => {
                current += increment;
                if (current >= target) {
                    element.textContent = prefix.replace(/[0-9]/g, '') + target + prefix.replace(/[^0-9]/g, '').replace(/[0-9]/g, '');
                    clearInterval(timer);
                } else {
                    element.textContent = prefix.replace(/[0-9]/g, '') + Math.floor(current) + prefix.replace(/[^0-9]/g, '').replace(/[0-9]/g, '');
                }
            }, 50);
        }

        // Animate counters when they come into view
        const counterObserver = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const counter = entry.target.querySelector('.stat-number');
                    if (counter && !counter.classList.contains('animated')) {
                        counter.classList.add('animated');
                        setTimeout(() => animateCounter(counter), 200);
                    }
                }
            });
        }, observerOptions);

        document.querySelectorAll('.stat-card').forEach(card => {
            counterObserver.observe(card);
        });

        // Add dynamic hover effects
        document.querySelectorAll('.program-card').forEach(card => {
            card.addEventListener('mouseenter', function() {
                this.style.transform = 'translateY(-8px) scale(1.02)';
            });
            
            card.addEventListener('mouseleave', function() {
                this.style.transform = 'translateY(0) scale(1)';
            });
        });

        // Parallax effect for hero section
        window.addEventListener('scroll', () => {
            const scrolled = window.pageYOffset;
            const hero = document.querySelector('.hero');
            if (hero) {
                hero.style.transform = `translateY(${scrolled * 0.5}px)`;
            }
        });

        // Dynamic gradient colors
        setInterval(() => {
            const gradients = [
                'linear-gradient(135deg, #8B4513 0%, #6D4C41 100%)',
                'linear-gradient(135deg, #8B4513 0%, #5D4037 100%)',
                'linear-gradient(135deg, #A0522D 0%, #6D4C41 100%)'
            ];
            const randomGradient = gradients[Math.floor(Math.random() * gradients.length)];
            
            document.querySelectorAll('.program-header, .hero').forEach(element => {
                if (Math.random() > 0.8) { // Only occasionally change
                    element.style.background = randomGradient;
                }
            });
        }, 10000); // Change every 10 seconds
    </script>
